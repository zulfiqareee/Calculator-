// Convert number string to Bengali digits if lang is bn
export const formatNumber = (val: string | number, lang: Language): string => {
  if (val === undefined || val === null || val === '') return '';
  const str = String(val);
  if (lang !== 'bn') return str;
  const bnDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
  return str.replace(/[0-9]/g, (w) => bnDigits[parseInt(w, 10)] || w);
};
